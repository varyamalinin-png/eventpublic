import { router } from 'expo-router';

/**
 * Переход на профиль пользователя — ОДНА точка на всё приложение.
 *
 * Свой профиль и чужой это два разных экрана: свой живёт в табе профиля
 * (со своими папками и настройками), чужой — это screens/UserProfileScreen,
 * который открывается внутри текущего раздела. Пока проверка «это я?» была
 * расписана по местам вызова, половина мест её просто не делала: из списка
 * участников чата собственный профиль открывался как ЧУЖОЙ — с шестерёнкой,
 * но без папок, — да ещё и внутри инбокса.
 *
 * Хуже того, UserProfileScreen на своём id перекидывал на таб профиля из
 * useEffect, но сам оставался смонтированным в стеке раздела (постабные
 * стеки сохраняют экраны — см. CLAUDE.md §1.1). Каждое возвращение в раздел
 * запускало перекидывание заново — отсюда «профиль открылся раз 8».
 */
export function openUserProfile(userId: string, currentUserId?: string | null): void {
  if (!userId) return;
  if (currentUserId && userId === currentUserId) {
    router.push('/profile');
    return;
  }
  router.push(`/profile/${userId}`);
}
