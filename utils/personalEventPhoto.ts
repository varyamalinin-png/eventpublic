import type { Event } from '../types';

/**
 * ТОЛЬКО персональное фото события («изменить фото для себя»), без общих
 * запасных вариантов.
 *
 * Отдельная функция нужна, потому что getEventPhotoForUser из контекста
 * решает две задачи сразу: отдаёт персональное фото И подставляет запасные
 * значения (общее фото события, аватар профиля события). Когда её поставили
 * первой при выборе картинки карточки, эти запасные варианты стали
 * выигрывать у фото, переданного самой карточке, — у только что созданного
 * события в карточке пропадало изображение, хотя в мини-карточке и в
 * профиле события оно было.
 *
 * Возвращает undefined, если персонального фото нет: тогда вызывающий код
 * использует свои данные в обычном порядке.
 */
export function getPersonalEventPhoto(
  event: Event | undefined,
  userId: string | undefined,
  viewerUserId?: string,
): string | undefined {
  const personal = (event as any)?.personalPhotos as Record<string, string> | undefined;
  if (!personal) return undefined;
  /**
   * Смотрим через чей-то профиль — показываем ТОЛЬКО его фото.
   *
   * Раньше при отсутствии фото у хозяина профиля подставлялось фото зрителя,
   * и в чужом профиле висела моя картинка события вместо той, что там должна
   * быть. Своё фото уместно лишь там, где профиля нет вовсе (лента, меморис).
   */
  if (viewerUserId) return personal[viewerUserId];
  if (userId && personal[userId]) return personal[userId];
  return undefined;
}
