-- Телефон обязателен при регистрации, но колонка добавляется nullable:
-- в таблице уже есть аккаунты без телефона, и NOT NULL к ним не применится.
-- Ужесточение — отдельной миграцией, после заполнения существующих записей.
ALTER TABLE "User" ADD COLUMN "phone" TEXT;

-- Уникальность нужна сразу: два аккаунта на один номер недопустимы.
-- В Postgres UNIQUE допускает несколько NULL, поэтому старые записи не мешают.
CREATE UNIQUE INDEX "User_phone_key" ON "User"("phone");
