import { Stack } from 'expo-router';

/**
 * Собственный стек раздела «Profile».
 *
 * Раньше экраны-детали (чужой профиль, профиль события, папка) лежали в
 * КОРНЕВОМ стеке, общем на все табы, и переключение раздела выбрасывало их
 * из стека: ушёл в другой таб и вернулся — вместо открытого профиля снова
 * начало ленты. Теперь у каждого раздела свой стек: экраны внутри него
 * остаются смонтированными и сохраняют состояние (скролл, загруженные
 * данные) — как в обычных мобильных соцсетях.
 *
 * Имя папки — ГРУППА в скобках: группы вырезаются из URL, поэтому адреса
 * экранов («/explore», «/inbox/messages») остались прежними.
 */
/**
 * Начальный экран стека — ОБЯЗАТЕЛЬНО явно.
 * В стек раздела входят и общие экраны (карта, календарь, профили,
 * папки), и без этой настройки навигатор брал первый попавшийся:
 * тап по табу Inbox открывал карту вместо списка чатов.
 */
export const unstable_settings = { initialRouteName: 'profile' };

export default function ProfileStackLayout() {
  // freezeOnBlur: неактивные экраны стека перестают перерисовываться,
  // оставаясь смонтированными (состояние и скролл сохраняются). В стеке
  // раздела теперь копится много экранов, и без заморозки каждый из них
  // продолжал реагировать на обновления контекста — отсюда нарастающие
  // подвисания и дёрганые свайпы после долгого хождения по приложению.
  // Тот же приём применялся в прежнем корневом стеке.
  /**
   * gestureResponseDistance расширяет зону жеста «назад».
   *
   * По умолчанию жест ловится только у самого края — 50 точек, начинать свайп
   * приходилось буквально с рамки. Ставим 120: заметно дальше от края, но не с
   * середины экрана — иначе жест начал бы спорить с горизонтальными жестами
   * внутри карточек (свайп карточки события, карусель фотографий).
   */
  return (
    <Stack
      screenOptions={{
        headerShown: false,
        freezeOnBlur: true,
        gestureEnabled: true,
        gestureResponseDistance: { start: 120 },
      }}
    />
  );
}
